"""Generate docker/cairn/failpoints.allowlist, or check it is current.

chaos_ctl's fault.failpoint tool accepts only the failpoint names in that
file (.kiro/specs/cairn-chaos-testing/ Requirement 3.2, task 7.2). The names
come from the fiu_do_on()/fiu_fail() calls in include/raft/, in the four
families the spec names, keeping only those chaos_node can actually reach.
A name chaos_node never evaluates would be accepted, take "effect", and
change nothing, which is worse than refusing it.

Every header that declares a name in those families must be classified
below, as reached by chaos_node or not and why, so a new header fails this
check until someone decides. chaos_node's own includes are checked too, so
switching it to another persistence engine or transport fails here rather
than leaving the allowlist describing the old one.

Usage: gen-cairn-failpoints.py           rewrite the allowlist
       gen-cairn-failpoints.py --check   exit 1 if it is not current
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOWLIST = ROOT / "docker/cairn/failpoints.allowlist"
CHAOS_NODE_MAIN = ROOT / "cmd/chaos_node/main.cpp"

FAMILIES = ("network", "persistence", "objstore", "state_machine")
NAME_RE = re.compile(
    r'fiu_(?:do_on|fail)\(\s*"(raft/(?:' + "|".join(FAMILIES) + r')/[A-Za-z0-9_/]+)"'
)

# Headers chaos_node compiles and runs these failpoints from.
REACHED = {
    "include/raft/file_persistence.hpp": "chaos_node's persistence engine",
    "include/raft/test_state_machine.hpp": "chaos_node's state machine",
    "include/raft/tcp_rpc.hpp": "chaos_node's plaintext RPC transport",
    "include/raft/tls_tcp_rpc.hpp": "chaos_node's mutual-TLS RPC transport (RPC_TLS_*)",
}

# Headers that declare names in the families but whose code chaos_node never
# runs. Their names are left out of the allowlist.
NOT_REACHED = {
    "include/raft/simulator_network.hpp":
        "the in-process simulator transport; chaos_node talks over tcp_rpc, which "
        "evaluates the same raft/network/* names",
    "include/raft/persistence.hpp":
        "the in-memory persistence engine; chaos_node uses file persistence",
    "include/raft/object_store_persistence.hpp":
        "object-store persistence; chaos_node uses file persistence (M4 adds it)",
    "include/raft/binary_file_persistence.hpp":
        "the binary segmented engine the disk-backed build cache runs on; chaos_node "
        "uses file persistence",
}

# Names in a reached header that the allowlisted modes cannot drive.
EXCLUDED = {
    "raft/persistence/barrier_delay":
        "reads its delay from failnum, which no allowlisted mode sets",
}

# chaos_node must still include what REACHED says it runs, and nothing from
# NOT_REACHED whose code it would then run.
REQUIRED_INCLUDES = (
    "raft/file_persistence.hpp",
    "raft/test_state_machine.hpp",
    "raft/tcp_rpc.hpp",
    "raft/tls_tcp_rpc.hpp",
)
FORBIDDEN_INCLUDES = ("raft/object_store_persistence.hpp", "raft/binary_file_persistence.hpp")

HEADER = """\
# Copyright (c) 2026 Clark Rawlins
# SPDX-License-Identifier: Apache-2.0

# Generated by scripts/gen-cairn-failpoints.py; do not edit. The failpoint
# names chaos_ctl's fault.failpoint accepts: those chaos_node evaluates, in
# the raft/{network,persistence,objstore,state_machine}/ families. The
# generator says which headers were left out and why.
"""


def scan():
    """Returns ({name: header}, [errors])."""
    names = {}
    errors = []
    for path in sorted((ROOT / "include/raft").glob("*.hpp")):
        rel = path.relative_to(ROOT).as_posix()
        found = set(NAME_RE.findall(path.read_text()))
        if not found:
            continue
        if rel in REACHED:
            for n in found:
                names.setdefault(n, rel)
        elif rel not in NOT_REACHED:
            errors.append(f"{rel} declares {sorted(found)} but is not classified in "
                          f"{Path(__file__).name}: add it to REACHED or NOT_REACHED")
    for rel in list(REACHED) + list(NOT_REACHED):
        if not (ROOT / rel).exists():
            errors.append(f"{rel} is classified but no longer exists")
    main = CHAOS_NODE_MAIN.read_text()
    for inc in REQUIRED_INCLUDES:
        if f"#include <{inc}>" not in main:
            errors.append(f"cmd/chaos_node/main.cpp no longer includes <{inc}>: "
                          "re-check REACHED")
    for inc in FORBIDDEN_INCLUDES:
        if f"#include <{inc}>" in main:
            errors.append(f"cmd/chaos_node/main.cpp now includes <{inc}>: "
                          "move it from NOT_REACHED to REACHED")
    for n in EXCLUDED:
        if n not in names:
            errors.append(f"EXCLUDED names {n}, which no reached header declares")
    return {n: h for n, h in names.items() if n not in EXCLUDED}, errors


def render(names):
    return HEADER + "\n" + "".join(f"{n}\n" for n in sorted(names))


def main(argv):
    check = argv[1:] == ["--check"]
    if argv[1:] and not check:
        print(__doc__, file=sys.stderr)
        return 2
    names, errors = scan()
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        return 1
    text = render(names)
    if check:
        current = ALLOWLIST.read_text() if ALLOWLIST.exists() else ""
        if current != text:
            print(f"{ALLOWLIST.relative_to(ROOT)} is stale: run "
                  f"scripts/gen-cairn-failpoints.py", file=sys.stderr)
            return 1
        return 0
    ALLOWLIST.parent.mkdir(parents=True, exist_ok=True)
    ALLOWLIST.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
