"""Generates a C++ service model for include/raft/aws_json_protocol.hpp.

Reads a botocore `service-2.json` (an AWS JSON 1.0 or 1.1 service: DynamoDB,
DynamoDB Streams, Kinesis) and writes a header holding the model as
`constexpr` tables: every shape, every structure member, every enum value,
every operation, all referring to each other by index.

Usage:
    gen_aws_json_shapes.py MODEL.json OUT.hpp --namespace NS [--check]

With --check, nothing is written: the script exits 1 when OUT.hpp differs
from what it would write. A ctest runs it that way for every checked-in
model, so a model upgrade without a regenerated header fails CI
(`.kiro/specs/dynamodb-compatible-api/` Requirement 2.4: the upgrade is a
reviewed change with the generated diff in the PR).

Output is deterministic: shapes and operations are sorted by name (lookups
binary-search them) and structure members keep the model's order,
so the same model always produces the same bytes.

Patterns are AWS's Java regular expressions. Most are also valid ECMAScript
and are kept for std::regex. Those using Java-only syntax (`\\p{...}`,
`\\uXXXX` UTF-16 escapes, which mean "any valid Unicode" in AWS's models)
are flagged `shape_flag_pattern_unchecked` and skipped by the validator.
Identity escapes ECMAScript forbids inside classes (`\\_`) are rewritten.
"""

import argparse
import json
import pathlib
import re
import sys

KINDS = {
    "structure": "structure",
    "list": "list",
    "map": "map",
    "string": "string",
    "blob": "blob",
    "boolean": "boolean",
    "integer": "integer",
    "long": "long_",
    "float": "float_",
    "double": "double_",
    "timestamp": "timestamp",
}

JAVA_ONLY = re.compile(r"\\p\{|\\P\{|\\u[0-9A-Fa-f]{4}")

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by scripts/gen_aws_json_shapes.py from
// {model} ({uid}).
// Do not edit: change the model and rerun the script.

#pragma once

#include <raft/aws_json_protocol.hpp>

#include <array>
#include <string_view>

namespace {ns} {{

// clang-format off
"""


def cxx_string(s):
    """A C++ string literal for s (ASCII escapes; UTF-8 bytes as octal)."""
    out = ['"']
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif 0x20 <= b < 0x7F:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    out.append('"')
    # "\\101" followed by a digit is fine in octal (max three digits), so no
    # splitting is needed.
    return "".join(out)


def ecmascript_pattern(p):
    """(pattern, unchecked) for a model pattern."""
    if JAVA_ONLY.search(p):
        return p, True
    # Inside and outside classes, escaping '_' is a Java identity escape
    # that ECMAScript (std::regex) rejects; it means a literal '_'.
    return p.replace("\\_", "_"), False


def int_bound(v):
    # Bounds are integral in every JSON-protocol model seen so far; a
    # fractional one would need a double field in `shape`.
    if isinstance(v, float):
        if v != int(v):
            raise SystemExit("fractional bound %r is not supported" % v)
        v = int(v)
    return v


def generate(model, model_label):
    meta = model["metadata"]
    if meta.get("protocol") != "json":
        raise SystemExit("not a JSON-protocol model: %r" % meta.get("protocol"))
    version = {"1.0": "v1_0", "1.1": "v1_1"}[meta["jsonVersion"]]
    shapes = model["shapes"]
    names = sorted(shapes)
    index = {n: i for i, n in enumerate(names)}

    members = []  # (name, shape index, required)
    enums = []
    rows = []
    for n in names:
        s = shapes[n]
        kind = KINDS.get(s["type"])
        if kind is None:
            raise SystemExit("shape %s: unsupported type %r" % (n, s["type"]))
        first = count = 0
        element = key = "aj::no_shape"
        if s["type"] == "structure":
            required = set(s.get("required", []))
            first = len(members)
            # Model order, which is the order AWS reports violations in.
            for mname in s.get("members", {}):
                m = s["members"][mname]
                members.append((mname, index[m["shape"]], mname in required))
            count = len(members) - first
        elif s["type"] == "list":
            element = str(index[s["member"]["shape"]])
        elif s["type"] == "map":
            key = str(index[s["key"]["shape"]])
            element = str(index[s["value"]["shape"]])
        elif s["type"] == "string" and "enum" in s:
            first = len(enums)
            enums.extend(s["enum"])
            count = len(s["enum"])
        flags = []
        if s.get("exception"):
            flags.append("aj::shape_flag_exception")
        if s.get("fault"):
            flags.append("aj::shape_flag_fault")
        if s.get("sensitive"):
            flags.append("aj::shape_flag_sensitive")
        pattern = ""
        if "pattern" in s:
            pattern, unchecked = ecmascript_pattern(s["pattern"])
            if unchecked:
                flags.append("aj::shape_flag_pattern_unchecked")
        has_min = "min" in s
        has_max = "max" in s
        rows.append(
            "    aj::shape{%s, aj::shape_kind::%s, %d, %d, %s, %s, %s, %s, %dLL, %dLL, %s, %s},"
            % (
                cxx_string(n),
                kind,
                first,
                count,
                element,
                key,
                "true" if has_min else "false",
                "true" if has_max else "false",
                int_bound(s.get("min", 0)),
                int_bound(s.get("max", 0)),
                cxx_string(pattern),
                " | ".join(flags) if flags else "aj::shape_flag_none",
            )
        )

    ops = []
    for oname in sorted(model["operations"]):
        o = model["operations"][oname]
        inp = str(index[o["input"]["shape"]]) if "input" in o else "aj::no_shape"
        out = str(index[o["output"]["shape"]]) if "output" in o else "aj::no_shape"
        ops.append("    aj::operation{%s, %s, %s}," % (cxx_string(oname), inp, out))

    lines = []
    lines.append("namespace aj = ::kythira::aws_json;\n")
    lines.append("inline constexpr std::array<aj::shape, %d> k_shapes{{" % len(rows))
    lines.extend(rows)
    lines.append("}};\n")
    lines.append("inline constexpr std::array<aj::member, %d> k_members{{" % max(len(members), 1))
    for mname, sidx, req in members:
        lines.append(
            "    aj::member{%s, %d, %s}," % (cxx_string(mname), sidx, "true" if req else "false")
        )
    if not members:
        lines.append("    aj::member{},")
    lines.append("}};\n")
    lines.append(
        "inline constexpr std::array<std::string_view, %d> k_enum_values{{" % max(len(enums), 1)
    )
    for e in enums:
        lines.append("    %s," % cxx_string(e))
    if not enums:
        lines.append('    "",')
    lines.append("}};\n")
    lines.append("inline constexpr std::array<aj::operation, %d> k_operations{{" % len(ops))
    lines.extend(ops)
    lines.append("}};\n")
    lines.append("/// The model, for aws_json::codec.")
    lines.append("inline constexpr aj::service_model k_model{")
    lines.append("    %s," % cxx_string(meta["targetPrefix"]))
    lines.append("    aj::json_version::%s," % version)
    lines.append("    k_shapes,")
    lines.append("    k_members,")
    lines.append("    k_enum_values,")
    lines.append("    k_operations,")
    lines.append("};\n")
    return lines, meta.get("uid", meta["targetPrefix"])


def render(model_path, ns, label):
    model = json.loads(pathlib.Path(model_path).read_text(encoding="utf-8"))
    lines, uid = generate(model, label)
    text = HEADER.format(model=label, uid=uid, ns=ns)
    text += "\n".join(lines)
    text += "// clang-format on\n\n}  // namespace %s\n" % ns
    return text


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model")
    ap.add_argument("out")
    ap.add_argument("--namespace", required=True)
    ap.add_argument(
        "--label",
        help="how the header names its model (default: the model path as given)",
    )
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(args.model, args.namespace, args.label or args.model)
    out = pathlib.Path(args.out)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(
                "%s is stale: rerun scripts/gen_aws_json_shapes.py %s %s --namespace %s%s"
                % (
                    args.out,
                    args.model,
                    args.out,
                    args.namespace,
                    " --label " + args.label if args.label else "",
                ),
                file=sys.stderr,
            )
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
