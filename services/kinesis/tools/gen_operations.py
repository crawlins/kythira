"""Generate the Kinesis operation table from the pinned botocore model.

Reads services/kinesis/model/service-2.json and writes
services/kinesis/include/kythira/kinesis/kinesis_operations.hpp: one entry
per operation, in model order (sorted by name), with whether its output is
an event stream (SubscribeToShard). The header is checked in so that a model
upgrade shows its effect in the pull request's diff
(.kiro/specs/kinesis-compatible-streams/ Requirement 2.4).

    gen_operations.py MODEL HEADER          write HEADER
    gen_operations.py MODEL HEADER --check  exit 1 if HEADER is stale

The ctest kinesis_operations_up_to_date runs the --check form.
"""

import argparse
import json
import pathlib
import sys

BOTOCORE_VERSION = "1.43.100"


def event_stream_output(model: dict, op: dict) -> bool:
    out = op.get("output", {}).get("shape")
    if not out:
        return False
    shapes = model["shapes"]
    for member in shapes[out].get("members", {}).values():
        if shapes.get(member.get("shape"), {}).get("eventstream"):
            return True
    return False


def render(model: dict) -> str:
    meta = model["metadata"]
    ops = sorted(model["operations"].items())
    lines = [
        "// Generated by services/kinesis/tools/gen_operations.py from",
        f"// services/kinesis/model/service-2.json (botocore {BOTOCORE_VERSION}). Do not edit:",
        "// change the model or the generator and rerun it.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace kythira::kinesis {",
        "",
        "/// One operation of the pinned Kinesis model.",
        "struct operation_info {",
        "    std::string_view _name;",
        "    /// The response is an HTTP/2 event stream (enhanced fan-out).",
        "    bool _event_stream = false;",
        "};",
        "",
        f'inline constexpr std::string_view botocore_version = "{BOTOCORE_VERSION}";',
        f'inline constexpr std::string_view api_version = "{meta["apiVersion"]}";',
        f'inline constexpr std::string_view json_version = "{meta["jsonVersion"]}";',
        "/// `X-Amz-Target` is this prefix, a dot and the operation name.",
        f'inline constexpr std::string_view target_prefix = "{meta["targetPrefix"]}";',
        "",
        "/// Every operation in the model, sorted by name.",
        f"inline constexpr std::array<operation_info, {len(ops)}> operations{{{{",
    ]
    for name, op in ops:
        flag = "true" if event_stream_output(model, op) else "false"
        lines.append(f'    {{"{name}", {flag}}},')
    lines += ["}};", "", "}  // namespace kythira::kinesis", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("model", type=pathlib.Path)
    ap.add_argument("header", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(json.loads(args.model.read_text(encoding="utf-8")))
    if args.check:
        current = args.header.read_text(encoding="utf-8") if args.header.exists() else ""
        if current != text:
            print(f"{args.header} is stale: rerun {sys.argv[0]} {args.model} {args.header}",
                  file=sys.stderr)
            return 1
        return 0
    if not args.header.exists() or args.header.read_text(encoding="utf-8") != text:
        args.header.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
