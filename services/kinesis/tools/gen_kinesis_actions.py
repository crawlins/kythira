"""Generate <kythira/kinesis/kinesis_actions.hpp> from AWS's service reference.

The input is the `kinesis` entry of AWS's machine-readable Service
Authorization Reference
(https://servicereference.us-east-1.amazonaws.com/v1/kinesis/kinesis.json),
pinned as tools/kinesis-service-reference.json. The output holds:

- kinesis_actions(): every action with the ARN formats of the resources it
  acts on and its condition keys (action keys plus the resources'), for the
  IAM authorizer's service registry;
- k_operation_actions: per API operation, every `kinesis` action AWS may
  check for it, and whether any of them writes. A superset: CreateStream
  lists AddTagsToStream, which it needs only when the request has Tags.
  The front end authorizes an operation as its same-named action and adds
  the tagging action itself when tags are present; an operation that
  writes nothing may be answered from any replica;
- kinesis_static_roles(): the static-key roles, derived from the
  reference's annotations: read-only is every action that neither writes
  nor manages permissions, read-write adds the data-plane writes
  (PutRecord, PutRecords).

Actions of other services (iam:PassRole for CreateChannel) are left out:
they are not ours to authorize.

Usage:
    gen_kinesis_actions.py REFERENCE OUT [--check]
"""

import argparse
import json
import pathlib
import sys

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/kinesis/tools/gen_kinesis_actions.py from
// services/kinesis/tools/kinesis-service-reference.json (AWS Service
// Authorization Reference, {version}). Do not edit; regenerate.

#pragma once

/// @file kinesis_actions.hpp
/// @brief The `kinesis` action table, the operation-to-action map and the
///        static-key roles (`.kiro/specs/kinesis-compatible-streams/`
///        Requirement 5.2, 5.3).

#include <raft/aws_request_authorizer.hpp>
#include <raft/static_key_authorizer.hpp>

#include <algorithm>
#include <array>
#include <string_view>

namespace kythira::kinesis {{

// clang-format off
"""

FOOTER = """\
// clang-format on

/// The entry for an API operation, or nullptr when the reference has none.
[[nodiscard]] constexpr auto find_operation_actions(std::string_view operation)
    -> const operation_actions* {
    const auto* it = std::lower_bound(
        k_operation_actions.begin(), k_operation_actions.end(), operation,
        [](const operation_actions& e, std::string_view name) { return e.operation < name; });
    return it != k_operation_actions.end() && it->operation == operation ? it : nullptr;
}

}  // namespace kythira::kinesis
"""


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def props(action):
    return action.get("Annotations", {}).get("Properties", {})


def generate(ref):
    resources = {r["Name"]: r for r in ref["Resources"]}
    actions = {a["Name"]: a for a in ref["Actions"]}
    out = [HEADER.format(version=ref.get("Version", "unversioned"))]

    out.append("/// Every `kinesis` action, its resource ARN formats and condition keys.")
    out.append("[[nodiscard]] inline auto kinesis_actions() -> aws_auth::aws_action_table {")
    out.append("    return {")
    out.append('        .service_prefix = "kinesis",')
    out.append("        .actions = {")
    for name in sorted(actions):
        a = actions[name]
        arns, keys = [], list(a.get("ActionConditionKeys", []))
        for r in a.get("Resources", []):
            res = resources[r["Name"]]
            arns += res["ARNFormats"]
            keys += res.get("ConditionKeys", [])
            keys += r.get("ConditionKeys", [])
        if not arns:
            arns = ["*"]
        keys = sorted(set(keys))
        out.append(
            "            {%s, {%s}, {%s}},"
            % (q(name), ", ".join(map(q, arns)), ", ".join(map(q, keys)))
        )
    out.append("        },")
    out.append("    };")
    out.append("}")
    out.append("")

    ops = sorted(ref["Operations"], key=lambda o: o["Name"])
    rows = []
    for o in ops:
        acts = sorted(
            a["Name"]
            for a in o.get("AuthorizedActions", [])
            if a.get("Service", "kinesis") == "kinesis"
        )
        writes = any(props(actions[a]).get("IsWrite", False) for a in acts if a in actions)
        rows.append((o["Name"], acts, writes))
    width = max(len(r[1]) for r in rows)
    out.append("/// Every `kinesis` action AWS may check for an API operation (a superset;")
    out.append("/// see the generator's docstring), and whether any of them writes.")
    out.append("struct operation_actions {")
    out.append("    std::string_view operation;")
    out.append("    std::array<std::string_view, %d> actions;  // unused slots empty" % width)
    out.append("    bool writes = false;")
    out.append("};")
    out.append("")
    out.append("/// Sorted by operation name.")
    out.append(
        "inline constexpr std::array<operation_actions, %d> k_operation_actions{{" % len(rows)
    )
    for name, acts, writes in rows:
        out.append(
            "    {%s, {%s}, %s}," % (q(name), ", ".join(map(q, acts)), "true" if writes else "false")
        )
    out.append("}};")
    out.append("")

    ro, rw = [], []
    for name in sorted(actions):
        p = props(actions[name])
        write, perm, data = (
            p.get(k, False) for k in ("IsWrite", "IsPermissionManagement", "IsDataPlane")
        )
        if not write and not perm:
            ro.append(name)
        elif write and data:
            rw.append(name)
    out.append("/// The static-key roles: read-only reads, read-write adds the data-plane")
    out.append("/// writes, admin is everything (`static_key_authorizer`).")
    out.append("[[nodiscard]] inline auto kinesis_static_roles() -> aws_auth::static_role_table {")
    out.append("    return {")
    out.append('        "kinesis",')
    out.append("        {%s}," % ", ".join(map(q, ro)))
    out.append("        {%s}," % ", ".join(map(q, rw)))
    out.append("    };")
    out.append("}")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("reference")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    text = generate(json.loads(pathlib.Path(args.reference).read_text(encoding="utf-8")))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
