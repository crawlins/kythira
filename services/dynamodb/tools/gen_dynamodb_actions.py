"""Generate <kythira/dynamodb/dynamodb_actions.hpp> from AWS's service reference.

The input is the `dynamodb` entry of AWS's machine-readable Service
Authorization Reference
(https://servicereference.us-east-1.amazonaws.com/v1/dynamodb/dynamodb.json),
pinned as tools/dynamodb-service-reference.json. The output holds:

- dynamodb_actions(): every action with the ARN formats of the resources
  it acts on and its condition keys (action keys plus the resources'), for
  the IAM authorizer's service registry;
- k_operation_actions: per API operation, every action AWS may check for
  it. A superset: CreateTable lists the replica, tagging and
  resource-policy actions it needs only when the request asks for those.
  The front end authorizes an operation as its same-named action; the
  operations that have none (TransactWriteItems, ExecuteStatement, ...)
  authorize per element in their own handlers, from this list;
- dynamodb_static_roles(): the static-key roles, derived from the
  reference's annotations: read-only is every action that neither writes
  nor manages permissions, read-write adds the data-plane writes.

Usage:
    gen_dynamodb_actions.py REFERENCE OUT [--check]
"""

import argparse
import json
import pathlib
import sys

HEADER = """\
// Copyright (c) 2026 Clark Rawlins
// SPDX-License-Identifier: Apache-2.0

// GENERATED by services/dynamodb/tools/gen_dynamodb_actions.py from
// services/dynamodb/tools/dynamodb-service-reference.json (AWS Service
// Authorization Reference, {version}). Do not edit; regenerate.

#pragma once

/// @file dynamodb_actions.hpp
/// @brief The `dynamodb` action table, the operation-to-action map and the
///        static-key roles (`.kiro/specs/dynamodb-compatible-api/`
///        Requirement 5.2, 5.3).

#include <raft/aws_request_authorizer.hpp>
#include <raft/static_key_authorizer.hpp>

#include <array>
#include <string_view>

namespace kythira::dynamodb {{

// clang-format off
"""

FOOTER = """\
// clang-format on

}  // namespace kythira::dynamodb
"""


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(ref):
    resources = {r["Name"]: r for r in ref["Resources"]}
    out = [HEADER.format(version=ref.get("Version", "unversioned"))]

    out.append("/// Every `dynamodb` action, its resource ARN formats and condition keys.")
    out.append("[[nodiscard]] inline auto dynamodb_actions() -> aws_auth::aws_action_table {")
    out.append("    return {")
    out.append('        .service_prefix = "dynamodb",')
    out.append("        .actions = {")
    for a in sorted(ref["Actions"], key=lambda a: a["Name"]):
        arns, keys = [], list(a.get("ActionConditionKeys", []))
        for r in a.get("Resources", []):
            res = resources[r["Name"]]
            arns += res["ARNFormats"]
            keys += res.get("ConditionKeys", [])
        if not arns:
            arns = ["*"]
        keys = sorted(set(keys))
        out.append(
            "            {%s, {%s}, {%s}},"
            % (q(a["Name"]), ", ".join(map(q, arns)), ", ".join(map(q, keys)))
        )
    out.append("        },")
    out.append("    };")
    out.append("}")
    out.append("")

    ops = sorted(ref["Operations"], key=lambda o: o["Name"])
    width = max(len(o.get("AuthorizedActions", [])) for o in ops)
    out.append("/// Every action AWS may check for an API operation (a superset; see the")
    out.append("/// generator's docstring).")
    out.append("struct operation_actions {")
    out.append("    std::string_view operation;")
    out.append("    std::array<std::string_view, %d> actions;  // unused slots empty" % width)
    out.append("};")
    out.append("")
    out.append("/// Sorted by operation name.")
    out.append(
        "inline constexpr std::array<operation_actions, %d> k_operation_actions{{" % len(ops)
    )
    for o in ops:
        acts = sorted(
            a["Name"] for a in o.get("AuthorizedActions", []) if a.get("Service", "dynamodb") == "dynamodb"
        )
        out.append("    {%s, {%s}}," % (q(o["Name"]), ", ".join(map(q, acts))))
    out.append("}};")
    out.append("")

    ro, rw = [], []
    for a in sorted(ref["Actions"], key=lambda a: a["Name"]):
        p = a.get("Annotations", {}).get("Properties", {})
        write, perm, data = (p.get(k, False) for k in ("IsWrite", "IsPermissionManagement", "IsDataPlane"))
        if not write and not perm:
            ro.append(a["Name"])
        elif write and data:
            rw.append(a["Name"])
    out.append("/// The static-key roles: read-only reads, read-write adds the data-plane")
    out.append("/// writes, admin is everything (`static_key_authorizer`).")
    out.append("[[nodiscard]] inline auto dynamodb_static_roles() -> aws_auth::static_role_table {")
    out.append("    return {")
    out.append('        "dynamodb",')
    out.append("        {%s}," % ", ".join(map(q, ro)))
    out.append("        {%s}," % ", ".join(map(q, rw)))
    out.append("    };")
    out.append("}")
    out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("reference")
    ap.add_argument("out")
    ap.add_argument("--check", action="store_true", help="fail if OUT is stale")
    args = ap.parse_args(argv)
    text = generate(json.loads(pathlib.Path(args.reference).read_text(encoding="utf-8")))
    out = pathlib.Path(args.out)
    if args.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("%s is stale; run %s" % (out, sys.argv[0]), file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
