"""Compiles services/iam/tools/aws_managed_policies.json into a C++ header.

Usage: gen_aws_managed_policies.py INPUT.json OUTPUT.hpp

The header defines kythira::iam::aws_managed_policy_data[], one entry per
policy: its name, path, default version id and document (compact JSON, as
a raw string literal). services/iam/CMakeLists.txt runs this at configure
time; the output lives in the build tree and is never committed.
"""

import json
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(sys.argv[1], encoding="utf-8") as f:
        data = json.load(f)

    entries = []
    seen = set()
    for p in data["policies"]:
        name, path, version = p["name"], p["path"], p["version_id"]
        if name.lower() in seen:
            raise SystemExit(f"duplicate policy {name}")
        seen.add(name.lower())
        if not (path.startswith("/") and path.endswith("/")):
            raise SystemExit(f"{name}: bad path {path!r}")
        doc = json.dumps(p["document"], separators=(",", ":"), sort_keys=False)
        if ')kythira"' in doc:
            raise SystemExit(f"{name}: document contains the raw-string delimiter")
        entries.append(
            f'    {{"{name}", "{path}", "{version}", R"kythira({doc})kythira"}},'
        )

    out = [
        "// Generated by services/iam/tools/gen_aws_managed_policies.py from",
        "// services/iam/tools/aws_managed_policies.json. Do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        "",
        "namespace kythira::iam {",
        "",
        "struct aws_managed_policy_entry {",
        "    std::string_view name;",
        "    std::string_view path;",
        "    std::string_view version_id;",
        "    std::string_view document;",
        "};",
        "",
        (
            f"inline constexpr std::array<aws_managed_policy_entry, {len(entries)}>"
            " aws_managed_policy_data{{"
        ),
        *entries,
        "}};",
        "",
        "}  // namespace kythira::iam",
        "",
    ]
    text = "\n".join(out)
    try:
        with open(sys.argv[2], encoding="utf-8") as f:
            if f.read() == text:
                return 0  # unchanged: keep the timestamp, avoid rebuilds
    except FileNotFoundError:
        pass
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
